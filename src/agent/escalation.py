"""
Правила перевода на человека из tenants/<TENANT>/knowledge/escalation_rules.md в виде кода.

Нужны там, где у «мозга» нет нашего инструмента transfer_to_department (профиль hermes_agent): очевидные случаи
(«соедините с оператором», угроза жалобой, спор по списанию) обрабатываются до модели, мгновенно и без риска,
что агент поспорит или начнёт расспрашивать. Спорные фразы правила не трогают, их разбирает модель.
"""

import re
from typing import Optional, Tuple

_ASK = re.compile(
    r"(соедин\w*|переключ\w*|переведи\w*|позов\w*|дайте|хочу|нужен|нужна|можно|давайте|требую|мне)\W+(?:\w+\W+){0,3}"
    r"(живо\w+\s+)?(человек\w*|оператор\w*|менеджер\w*|специалист\w*|руководител\w*)"
)
_OPERATOR_FIRST = re.compile(r"(оператор\w*|менеджер\w*)\W+(мне|дайте|пожалуйста|сюда)")
_NOT_US = re.compile(r"(друг\w+|мобильн\w+|сотов\w+)\s+оператор|оператор\w*\s+связи|от\s+оператор")
_ANGRY = re.compile(
    r"жалоб|в суд|через суд|расторг|прокуратур|роспотребнадзор|роскомнадзор|достали|задолбал|безобразие|издевательств|возмутительн"
)
_CHARGE = re.compile(r"списал\w*|списано|сняли|снял\w*|удержал\w*")
_CHARGE_DISPUTE = re.compile(r"не понима\w*|непонятн\w*|не знаю,? за что|за что|не подключал\w*|не просил\w*|без моего|не мои")

Transfer = Tuple[str, str, str]  # отдел, причина, фраза перед переводом


def escalation_intent(text: str) -> Optional[Transfer]:
    t = text.lower().replace("ё", "е")
    if _ANGRY.search(t):
        return "менеджер", "высокий риск недовольства клиента", "Понимаю вас, давайте я сразу соединю с менеджером. Одну секунду."
    if not _NOT_US.search(t) and (_ASK.search(t) or _OPERATOR_FIRST.search(t)):
        return "менеджер", "абонент явно попросил человека", "Конечно, соединяю с оператором. Одну секунду."
    if _CHARGE.search(t) and _CHARGE_DISPUTE.search(t):
        return "биллинг", "расхождение по счёту, нужна проверка", "Понимаю, это нужно проверить по вашему счёту. Соединяю со специалистом по начислениям, одну секунду."
    return None
